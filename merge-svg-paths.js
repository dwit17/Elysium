/**
 * merge-svg-paths.js
 *
 * USAGE:
 *   node merge-svg-paths.js <input.svg> [output.svg]
 *
 * WHAT IT DOES:
 *   1. Reads an SVG with many <path> elements (the raw illustration export).
 *   2. Parses each path's `d` attribute and approximates its leftmost X centroid.
 *   3. Sorts paths ascending by centroid → left-to-right draw order.
 *   4. Concatenates all `d` values into one compound `d` string.
 *   5. Writes a new SVG containing exactly ONE <path id="sanctuary-line-art">
 *      with the merged compound `d`, preserving the original viewBox.
 *
 * REQUIREMENTS:
 *   node >= 16  (stdlib only — no npm install)
 *
 * OUTPUT:
 *   Copy the generated file to: public/svg-section4.svg
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const [,, inputArg, outputArg] = process.argv;
if (!inputArg) {
  console.error('Usage: node merge-svg-paths.js <input.svg> [output.svg]');
  process.exit(1);
}

const inputFile  = path.resolve(inputArg);
const outputFile = outputArg
  ? path.resolve(outputArg)
  : inputFile.replace(/\.svg$/i, '-merged.svg');

if (!fs.existsSync(inputFile)) {
  console.error(`File not found: ${inputFile}`);
  process.exit(1);
}

const raw = fs.readFileSync(inputFile, 'utf8');

// Extract opening <svg …> tag (preserves viewBox, xmlns, etc.)
const svgOpenMatch = raw.match(/<svg([^>]*)>/i);
if (!svgOpenMatch) {
  console.error('No <svg> tag found in input file.');
  process.exit(1);
}
const svgAttrs = svgOpenMatch[1];

// Collect all <path …/> or <path …></path> elements
const pathRegex = /<path\b([^>]*?)(?:\/>|>[\s\S]*?<\/path>)/gi;
const pathMatches = [...raw.matchAll(pathRegex)];

if (pathMatches.length === 0) {
  console.error('No <path> elements found. Run Figma "Flatten" first if paths are nested in <g> with transforms.');
  process.exit(1);
}

console.log(`Found ${pathMatches.length} <path> elements.`);

// Extract `d` attribute from attrs string
function extractD(attrs) {
  const m = attrs.match(/\bd\s*=\s*["']([^"']*)["']/i);
  return m ? m[1].trim() : '';
}

// Approximate leftmost X value from path `d` string for sort ordering
function approxLeftmostX(d) {
  const commands = d.match(/[MmLlHhVvCcSsQqTtAaZz]|[-\d.]+(?:e[-+]?\d+)?/gi) || [];
  let isX = true;
  let lastCmd = '';
  const xVals = [];

  for (const tok of commands) {
    if (/^[MmLlCcSsQqTtAa]/i.test(tok)) { lastCmd = tok; isX = true;  continue; }
    if (/^[Hh]/i.test(tok))              { lastCmd = tok; isX = true;  continue; }
    if (/^[Vv]/i.test(tok))              { lastCmd = tok; isX = false; continue; }
    if (/^[Zz]/.test(tok))              { continue; }

    const n = parseFloat(tok);
    if (isNaN(n)) continue;

    if (isX) { xVals.push(n); isX = false; }
    else      { isX = true; }
  }

  return xVals.length > 0 ? Math.min(...xVals) : 0;
}

// Build sortable path objects
const paths = pathMatches
  .map((m, idx) => ({ idx, d: extractD(m[1]), leftX: 0, attrs: m[1] }))
  .filter(p => p.d.length > 0)
  .map(p => ({ ...p, leftX: approxLeftmostX(p.d) }));

if (paths.length === 0) {
  console.error('No non-empty `d` attributes found.');
  process.exit(1);
}

// Sort left-to-right
paths.sort((a, b) => a.leftX - b.leftX);

console.log('Sorted paths (leftmost X → rightmost X):');
paths.forEach((p, i) => {
  console.log(`  [${String(i).padStart(3)}] DOM index ${String(p.idx).padStart(3)}  leftX ≈ ${p.leftX.toFixed(1)}`);
});

// Concatenate into one compound d string
const compoundD = paths.map(p => p.d).join(' ');

// Sniff stroke colour from first path that declares one, else Elysium gold
function sniff(attrs, attr) {
  const m = attrs.match(new RegExp(`\\b${attr}\\s*=\\s*["']([^"']*)["']`, 'i'));
  return m ? m[1] : null;
}
let stroke      = null;
let strokeWidth = null;
for (const m of pathMatches) {
  stroke      = stroke      || sniff(m[1], 'stroke');
  strokeWidth = strokeWidth || sniff(m[1], 'stroke-width');
  if (stroke && strokeWidth) break;
}
stroke      = stroke      || '#c9a84c';
strokeWidth = strokeWidth || '1.5';

// Write merged SVG
const output = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Merged compound-path SVG for Elysium Section 4 scroll-draw.
  Generated by: node merge-svg-paths.js ${path.basename(inputFile)}
  Paths merged: ${paths.length}
  Draw order: sorted left-to-right by horizontal centroid

  INSTALL:
    copy ${path.basename(outputFile)} public\\svg-section4.svg   (Windows)
    cp   ${path.basename(outputFile)} public/svg-section4.svg    (Unix)
-->
<svg${svgAttrs}>
  <path
    id="sanctuary-line-art"
    d="${compoundD}"
    stroke="${stroke}"
    stroke-width="${strokeWidth}"
    stroke-linecap="round"
    stroke-linejoin="round"
    fill="none"
  />
</svg>
`;

fs.writeFileSync(outputFile, output, 'utf8');
console.log(`\n✔  Written → ${outputFile}`);
console.log(`   Paths merged : ${paths.length}`);
console.log(`   Compound d   : ${compoundD.length} chars`);
console.log(`\nNext: copy to public/svg-section4.svg then reload localhost:3000`);
